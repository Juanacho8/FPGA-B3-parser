"""Support: answer keys.

Intent log (JSON Lines): one row per message on the wire, in wire order
(packet order, then index in packet), heartbeats included:

    {"channel", "sequenceVersion", "sequenceNumber", "index", "sendingTime",
     "templateId", "blockLength", "version", "instrument",
     "fields": {every field: wire value},
     "null": [fields whose wire value is their null]}

blockLength and version are the message header's (the schema's unless the
publisher encoded a newer-schema message). A template the schema does not
have gets fields {"body": hex}. The last part of a News also carries
"news": {"newsID", "headline", "text"} with the reassembled text.

fields holds every non-constant field of the template. Fields the publisher
left out get their null from layouts.py. An optional field is listed in
"null" when its wire value equals its null, whoever set it: that is what a
decoder sees. Chars are strings; a null char field is "".

Book key (JSON Lines): the true top 5 levels per side for every instrument at
checkpoints, each right after an event's EndOfEvent message:

    {"key": [channel, sequenceVersion, sequenceNumber, index],
     "books": {instrument: {"as_of": [placement], "bids": [[price, qty, orders]],
                            "offers": [...]}}}

Channels are packetized independently, so when the checkpoint message goes
out another channel may still hold earlier messages in an open packet. Each
instrument therefore carries "as_of": the placement of the last message
published on its own channel. A client replaying the wire compares that
instrument's book when its channel reaches as_of.

Must not: decode the generated bytes. Answer keys come from intent
(Published.fields and the packetizer's own heartbeat records), so an
encoder bug cannot hide itself.
See docs/FEED_GENERATOR_CONTEXT.md section 10 (Outputs).
"""

import json
from array import array
from pathlib import Path

from b3gen import layouts
from b3gen.packet import HEARTBEAT_SEQUENCE_NUMBER, Heartbeat, Placement
from b3gen.pcap import PcapWriter

SEQUENCE_TEMPLATE = layouts.TEMPLATES_BY_NAME["Sequence_2"].id


def wire_fields(template_id, fields):
    """(every field -> wire value, [null field names]) for one message."""
    template = layouts.TEMPLATES[template_id]
    if template.groups:
        raise NotImplementedError(f"{template.name}: groups in the intent log")
    out = {}
    nulls = []
    for f in template.fields:
        if f.primitive == "composite":
            raise NotImplementedError(f"{template.name}.{f.name}: composite in the intent log")
        if f.deprecated is not None or f.name not in fields:
            if f.presence != "optional":
                raise ValueError(f"{template.name}.{f.name}: required field missing")
            value = f.null
        else:
            value = fields[f.name]
        if f.primitive == "char":
            if value == 0 and type(value) is int:
                value = ""
            elif isinstance(value, bytes):
                value = value.decode("ascii")
        out[f.name] = value
        is_null = f.presence == "optional" and (
            value == f.null or (f.primitive == "char" and value == ""))
        if is_null:
            nulls.append(f.name)
    for d in template.var_data:
        value = fields.get(d.name, b"")
        out[d.name] = value.decode("utf-8") if isinstance(value, bytes) else value
    return out, nulls


def message_row(p, msg):
    """Intent row for one Published message at Placement p."""
    if msg.template_id in layouts.TEMPLATES:
        fields, nulls = wire_fields(msg.template_id, msg.fields)
    else:
        fields, nulls = {"body": msg.fields["body"].hex()}, []
    row = _row(p, msg.template_id, msg.instrument, fields, nulls,
               msg.block_length, msg.version)
    row.update(msg.annotations or {})
    return row


def heartbeat_row(hb):
    fields, nulls = wire_fields(SEQUENCE_TEMPLATE, {"nextSeqNo": hb.next_seq_no})
    return _row(hb.placement, SEQUENCE_TEMPLATE, None, fields, nulls)


def intent_rows(published, packetized):
    """Rows for every published message (tagged by its index in published)
    and every heartbeat, sorted in wire order. (The in-memory path; streamed
    runs write the same rows packet by packet.)"""
    rows = []
    for tag, msg in enumerate(published):
        p = packetized.placements[tag]
        rows.append(((p.packet_position, p.index), message_row(p, msg)))
    for hb in packetized.heartbeats:
        p = hb.placement
        rows.append(((p.packet_position, p.index), heartbeat_row(hb)))
    rows.sort(key=lambda r: r[0])
    return [row for _, row in rows]


class PlacementTable:
    """tag -> Placement for every message of a streamed run, in compact
    arrays (tags are 0, 1, 2, ... in publication order)."""

    def __init__(self):
        self._cols = [array("q") for _ in range(6)]

    def set(self, tag, p):
        for col, value in zip(self._cols, (p.channel, p.sequence_version, p.sequence_number,
                                           p.index, p.sending_time, p.packet_position)):
            if len(col) <= tag:
                col.extend([-1] * (tag + 1 - len(col)))
            col[tag] = value

    def __getitem__(self, tag):
        values = [col[tag] for col in self._cols]
        if values[0] < 0:
            raise KeyError(tag)
        return Placement(*values)

    def __contains__(self, tag):
        return tag < len(self._cols[0]) and self._cols[0][tag] >= 0


class StreamWriter:
    """Writes Feed A's pcap and the intent log as the packetizer hands over
    each packet (Packetizer sink), then forgets the packet's messages."""

    def __init__(self, out_dir, published, channel_map, src_ip, src_port):
        self.published = published          # tag -> Published, emptied as packets go out
        self.placements = PlacementTable()
        self.packets = []                   # (time_ns, channel, bytes): kept for Feed B
        self._pcap = PcapWriter(Path(out_dir) / "feedA.pcap", channel_map=channel_map,
                                src_ip=src_ip, src_port=src_port)
        self._intent = open(Path(out_dir) / "intent.jsonl", "w", encoding="utf-8")

    def __call__(self, position, time_ns, channel, version, seq, contents, data):
        self.packets.append((time_ns, channel, data))
        self._pcap.write(time_ns, channel, data)
        if seq == HEARTBEAT_SEQUENCE_NUMBER:
            p = Placement(channel, version, seq, 0, time_ns, position)
            self._line(heartbeat_row(Heartbeat(p, contents)))
            return
        for index, tag in enumerate(contents):
            p = Placement(channel, version, seq, index, time_ns, position)
            self.placements.set(tag, p)
            self._line(message_row(p, self.published.pop(tag)))

    def _line(self, row):
        self._intent.write(json.dumps(row, separators=(",", ":"), ensure_ascii=False))
        self._intent.write("\n")

    def close(self):
        self._pcap.close()
        self._intent.close()


def _row(p, template_id, instrument, fields, nulls, block_length=None, version=None):
    if block_length is None:
        block_length = layouts.TEMPLATES[template_id].block_length
    return {"channel": p.channel, "sequenceVersion": p.sequence_version,
            "sequenceNumber": p.sequence_number, "index": p.index,
            "sendingTime": p.sending_time, "templateId": template_id,
            "blockLength": block_length,
            "version": layouts.SCHEMA_VERSION if version is None else version,
            "instrument": instrument, "fields": fields, "null": nulls}


def placement_key(p):
    return [p.channel, p.sequence_version, p.sequence_number, p.index]


def book_key_rows(checkpoints, packetized):
    """checkpoints: [(eoe tag, {instrument: (as_of tag, (bids, offers))})]."""
    rows = []
    for tag, books in checkpoints:
        out = {}
        for name, (as_of, (bids, offers)) in books.items():
            out[name] = {"as_of": placement_key(packetized.placements[as_of]),
                         "bids": [list(level) for level in bids],
                         "offers": [list(level) for level in offers]}
        rows.append({"key": placement_key(packetized.placements[tag]), "books": out})
    return rows


def write_jsonl(path, rows):
    with open(path, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, separators=(",", ":"), ensure_ascii=False))
            f.write("\n")
