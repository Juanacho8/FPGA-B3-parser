#!/usr/bin/env python3
"""gen_instruments: writes the C++ baseline's instrument table from config.toml.

What it does:
  Reads the feed generator's config (feed_generator/config.toml by default)
  and writes the plain-text table b3_decode --instruments loads
  (docs/DESIGN.md 4.4): one line per instrument, "securityID channel",
  in config order, with a comment naming the instrument. Lines starting with
  # are comments.

What it must not do:
  Import b3gen. It reads the TOML file with the standard library only.

Usage:
  python3 tools/gen_instruments.py [--config feed_generator/config.toml] -o instruments.txt
"""

import argparse
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]


def table_text(config_path):
    config = tomllib.loads(Path(config_path).read_text(encoding="utf-8"))
    instruments = config.get("instruments")
    if not isinstance(instruments, list) or not instruments:
        raise SystemExit(f"{config_path}: no [[instruments]]")
    lines = [f"# Instrument table for b3_decode --instruments (docs/DESIGN.md 4.4).",
             f"# Generated by tools/gen_instruments.py from {Path(config_path).name}.",
             "# securityID channel"]
    for i in instruments:
        sid, ch, name = i.get("security_id"), i.get("channel"), i.get("name")
        if not isinstance(sid, int) or not isinstance(ch, int):
            raise SystemExit(f"{config_path}: instrument {name!r} needs integer security_id and channel")
        lines.append(f"{sid} {ch}  # {name}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--config", default=str(REPO / "feed_generator" / "config.toml"))
    ap.add_argument("-o", "--out", required=True)
    args = ap.parse_args(argv)
    Path(args.out).write_text(table_text(args.config), encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
